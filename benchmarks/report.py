"""Assemble docs/validation-results.md from the benchmark outputs in results/.

    python benchmarks/report.py
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path

import pandas as pd
from _common import RESULTS, summarize

import graphdml

DOC = Path(__file__).parents[1] / "docs" / "validation-results.md"
COLS = ["graph", "effect", "coverage", "se_over_sd", "rmse", "bias", "n_focal", "in_band"]


def coverage_section() -> str:
    out = ["## Coverage", ""]
    df = pd.read_csv(RESULTS / "coverage.csv")
    s = summarize(df, ["dgp", "nuisances", "graph", "effect"])
    n = df["seed"].nunique()
    half = 3 * (0.95 * 0.05 / n) ** 0.5
    s["in_band"] = s["coverage"].between(0.95 - half, 0.95 + half)
    out.append(
        f"Stage 1: {n} seeds, 2,000-node graphs, nominal 95% intervals, band 0.95 ± {half:.3f}. "
        "`se_over_sd` is the mean standard error divided by the empirical standard deviation of "
        "the estimates (1 = calibrated)."
    )
    for (dgp, nz), g in s.groupby(["dgp", "nuisances"], sort=False):
        out += ["", f"**{dgp}, {nz} nuisances**", "", g[COLS].to_markdown(index=False,
                                                                        floatfmt=".3f")]
    confirm = RESULTS / "coverage_confirm.csv"
    if confirm.exists():
        c = pd.read_csv(confirm)
        cs = summarize(c, ["dgp", "nuisances", "graph", "effect"])
        m = c["seed"].nunique()
        h2 = 3 * (0.95 * 0.05 / m) ** 0.5
        cs["in_band"] = cs["coverage"].between(0.95 - h2, 0.95 + h2)
        out += ["", f"Stage 2 (confirmation of flagged cells): {m} fresh seeds, band "
                    f"0.95 ± {h2:.3f}.", "",
                cs[["dgp", "nuisances", *COLS]].to_markdown(index=False, floatfmt=".3f")]
    return "\n".join(out)


def design_section() -> str:
    df = pd.read_csv(RESULTS / "design_choices.csv")
    s = summarize(df, ["dataset", "effect", "config"])
    n = df["seed"].nunique()
    s["cell"] = s.apply(
        lambda r: f"{100 * r.rel_bias:+.1f}% · {r.coverage:.2f} · {r.rmse:.3g}", axis=1
    )
    table = s.pivot_table(index=["dataset", "effect"], columns="config", values="cell",
                          aggfunc="first", sort=False)
    table = table[list(dict.fromkeys(s["config"]))]
    return "\n".join([
        "## Design choices",
        "",
        f"{n} seeds per dataset, default machine-learning nuisances (regularised gradient "
        "boosting). Each cell: relative bias · coverage of 95% intervals · RMSE.",
        "",
        table.reset_index().to_markdown(index=False),
    ])


def tradeoff_section() -> str:
    df = pd.read_csv(RESULTS / "focal_tradeoff.csv")
    s = summarize(df, ["dataset", "effect", "method"])
    cols = ["dataset", "effect", "method", "rel_bias", "rmse", "coverage", "se_over_sd"]
    return "\n".join([
        "## The cost of the focal set",
        "",
        f"{df['seed'].nunique()} seeds, default learners. Using all nodes (no focal set) "
        "lowers RMSE substantially, but its i.i.d. variance ignores dependence between "
        "neighbors' scores, so for most effects the standard errors are too small "
        "(se_over_sd < 1) and coverage falls below nominal. Closing this gap with a "
        "dependence-robust variance and cluster cross-fitting is the top V1.1 item.",
        "",
        s[cols].to_markdown(index=False, floatfmt=".3f"),
    ])


def ate_section() -> str:
    path = RESULTS / "ate_coverage.md"
    if not path.exists():
        return ""
    return "## Total effect (ATE)\n" + path.read_text().split("\n", 2)[2]


def lastfm_section() -> str:
    path = RESULTS / "lastfm_experiment.csv"
    if not path.exists():
        return ""
    df = pd.read_csv(path)
    s = summarize(df, ["effect", "method"])
    cols = ["effect", "method", "rel_bias", "rmse", "coverage", "se_over_sd", "n_focal"]
    return "\n".join([
        "## Real network: LastFM Asia (semi-synthetic)",
        "",
        f"{df['seed'].nunique()} replications on the real LastFM Asia graph (7,624 users) with "
        "real covariates; treatment and outcome simulated with known effects (direct 2.0, "
        "peer 3.0). See `make_lastfm_promo`.",
        "",
        s[cols].to_markdown(index=False, floatfmt=".3f"),
    ])


if __name__ == "__main__":
    header = (
        "# Validation results\n\n"
        f"Generated by `benchmarks/report.py` on {dt.date.today()} for graphdml "
        f"{graphdml.__version__}. The protocol and pass criteria are in "
        "[the validation protocol](../docs/validation.md); raw per-seed results are in "
        "`benchmarks/results/*.csv`.\n"
    )
    DOC.write_text("\n\n".join([header, coverage_section(), design_section(),
                                ate_section(), tradeoff_section(), lastfm_section()]) + "\n")
    print(f"wrote {DOC}")
